/// Grid de espaçamento do Design System Seapruma (PPVDigital).
/// Promove ritmo visual consistente, arejamento e leveza nas telas.
abstract final class AppSpacing {
  /// 2.0 - Micro espaçamento (ajuste fino de alinhamento)
  static const double xxs = 2.0;

  /// 4.0 - Espaçamento mínimo (entre ícone e texto compacto, tags)
  static const double xs = 4.0;

  /// 8.0 - Espaçamento pequeno (paddings internos compactos, gaps entre chips)
  static const double sm = 8.0;

  /// 12.0 - Espaçamento médio-pequeno (separação de campos, listas compactas)
  static const double mdSm = 12.0;

  /// 16.0 - Espaçamento padrão / base (margens laterais de tela, padding de cards)
  static const double md = 16.0;

  /// 20.0 - Espaçamento intermediário (separação entre seções menores)
  static const double mdLg = 20.0;

  /// 24.0 - Espaçamento grande (espaço entre grupos de cards, cabeçalhos)
  static const double lg = 24.0;

  /// 32.0 - Espaçamento extra grande (separações de grandes blocos visuais)
  static const double xl = 32.0;

  /// 48.0 - Espaçamento máximo (respiro de topo, telas vazias)
  static const double xxl = 48.0;
}
